DO $$
BEGIN
    -- Код ошибки (enum)
    BEGIN
        CREATE TYPE parameter_error_code AS ENUM (
            'EQUIPMENT_EMPTY',
            'EQUIPMENT_UNKNOWN',
            'REQUIRED',
            'NOT_APPLICABLE',
            'BELOW_MIN',
            'ABOVE_MAX'
        );
        COMMENT ON TYPE parameter_error_code IS 'Коды ошибок входных параметров';
    EXCEPTION
        WHEN duplicate_object THEN
            RAISE NOTICE 'Тип parameter_error_code уже существует';
        WHEN OTHERS THEN
            RAISE NOTICE 'Ошибка при создании типа parameter_error_code: %', SQLERRM;
            RAISE;
    END;

    -- Справочник сообщений об ошибках
    BEGIN
        CREATE TABLE IF NOT EXISTS parameter_error_types (
            id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            code parameter_error_code NOT NULL UNIQUE,
            message VARCHAR(200) NOT NULL
        );
        COMMENT ON TABLE parameter_error_types IS 'Справочник ошибок входных параметров';
        COMMENT ON COLUMN parameter_error_types.id IS 'Уникальный идентификатор записи';
        COMMENT ON COLUMN parameter_error_types.code IS 'Код ошибки, по нему функция проверки находит сообщение';
        COMMENT ON COLUMN parameter_error_types.message IS 'Шаблон сообщения для format(): %1$s - значение, %2$s - минимум, %3$s - максимум';
    EXCEPTION
        WHEN OTHERS THEN
            RAISE NOTICE 'Ошибка при создании таблицы parameter_error_types: %', SQLERRM;
            RAISE;
    END;

    -- Тексты сообщений
    BEGIN
        INSERT INTO parameter_error_types (code, message) VALUES
            ('EQUIPMENT_EMPTY', 'Не указан тип оборудования'),
            ('EQUIPMENT_UNKNOWN', 'Неизвестный тип оборудования (id=%1$s)'),
            ('REQUIRED', 'Не заполнено'),
            ('NOT_APPLICABLE', 'Не используется для выбранного оборудования'),
            ('BELOW_MIN', 'Значение %1$s меньше минимального %2$s'),
            ('ABOVE_MAX', 'Значение %1$s больше максимального %3$s')
        ON CONFLICT (code) DO NOTHING;
    EXCEPTION
        WHEN OTHERS THEN
            RAISE NOTICE 'Ошибка при заполнении parameter_error_types: %', SQLERRM;
            RAISE;
    END;

    RAISE NOTICE 'Миграция выполнена успешно';
END $$;